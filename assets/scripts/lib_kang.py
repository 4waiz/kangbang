_BOX_FACES = [
    (0, 1, 2, 3),  # -Z
    (4, 7, 6, 5),  # +Z
    (0, 4, 5, 1),  # -Y
    (2, 6, 7, 3),  # +Y
    (0, 3, 7, 4),  # -X
    (1, 5, 6, 2),  # +X
]


def box(
    name: str,
    center: tuple[float, float, float],
    size: tuple[float, float, float],
    material: str = MAT_BODY,
    rotation: tuple[float, float, float] = (0.0, 0.0, 0.0),
    taper: tuple[float, float] = (1.0, 1.0),
) -> bpy.types.Object:
    """
    Axis-aligned box (before `rotation`, in degrees).

    `taper` scales the +Z face in X and Y, which turns a box into a truncated
    wedge - the single most useful shape for low-poly weapon bodies.
    """
    hx, hy, hz = size[0] / 2.0, size[1] / 2.0, size[2] / 2.0
    tx, ty = taper
    verts = [
        (-hx, -hy, -hz),
        (hx, -hy, -hz),
        (hx, hy, -hz),
        (-hx, hy, -hz),
        (-hx * tx, -hy * ty, hz),
        (hx * tx, -hy * ty, hz),
        (hx * tx, hy * ty, hz),
        (-hx * tx, hy * ty, hz),
    ]
    obj = mesh_from_data(name, verts, list(_BOX_FACES), material)
    obj.location = center
    obj.rotation_euler = tuple(math.radians(a) for a in rotation)
    return obj


def cylinder(
    name: str,
    center: tuple[float, float, float],
    radius: float,
    length: float,
    segments: int = 8,
    material: str = MAT_BODY,
    axis: str = "Z",
    radius_top: float | None = None,
    rotation: tuple[float, float, float] = (0.0, 0.0, 0.0),
    smooth: bool = True,
) -> bpy.types.Object:
    """N-gon prism/cone along `axis`. 8 segments reads as round at game scale."""
    if radius_top is None:
        radius_top = radius
    half = length / 2.0
    verts: list[tuple[float, float, float]] = []
    for i in range(segments):
        a = (i / segments) * math.tau
        verts.append((math.cos(a) * radius, math.sin(a) * radius, -half))
    for i in range(segments):
        a = (i / segments) * math.tau
        verts.append((math.cos(a) * radius_top, math.sin(a) * radius_top, half))

    faces: list[tuple[int, ...]] = []
    for i in range(segments):
        j = (i + 1) % segments
        faces.append((i, j, segments + j, segments + i))
    faces.append(tuple(reversed(range(segments))))
    faces.append(tuple(range(segments, segments * 2)))

    obj = mesh_from_data(name, verts, faces, material, smooth=smooth)
    rot = list(rotation)
    if axis.upper() == "X":
        rot[1] += 90.0
    elif axis.upper() == "Y":
        rot[0] += 90.0
    obj.location = center
    obj.rotation_euler = tuple(math.radians(a) for a in rot)
    return obj


def wedge(
    name: str,
    center: tuple[float, float, float],
    size: tuple[float, float, float],
    material: str = MAT_BODY,
    rotation: tuple[float, float, float] = (0.0, 0.0, 0.0),
) -> bpy.types.Object:
    """Triangular prism rising along +Z."""
    hx, hy, hz = size[0] / 2.0, size[1] / 2.0, size[2] / 2.0
    verts = [
        (-hx, -hy, -hz),
        (hx, -hy, -hz),
        (hx, hy, -hz),
        (-hx, hy, -hz),
        (-hx, hy, hz),
        (hx, hy, hz),
    ]
    faces = [
        (0, 1, 2, 3),
        (3, 2, 5, 4),
        (0, 4, 5, 1),
        (0, 3, 4),
        (1, 5, 2),
    ]
    obj = mesh_from_data(name, verts, faces, material)
    obj.location = center
    obj.rotation_euler = tuple(math.radians(a) for a in rotation)
    return obj


def sphere(
    name: str,
    center: tuple[float, float, float],
    radius: float,
    material: str = MAT_BODY,
    rings: int = 6,
    segments: int = 8,
) -> bpy.types.Object:
    """Low-poly UV sphere; used for helmets, pods and energy cores."""
    verts: list[tuple[float, float, float]] = [(0.0, 0.0, radius)]
    for r in range(1, rings):
        phi = math.pi * r / rings
        z = math.cos(phi) * radius
        rr = math.sin(phi) * radius
        for s in range(segments):
            a = (s / segments) * math.tau
            verts.append((math.cos(a) * rr, math.sin(a) * rr, z))
    verts.append((0.0, 0.0, -radius))

    faces: list[tuple[int, ...]] = []
    for s in range(segments):
        faces.append((0, 1 + s, 1 + (s + 1) % segments))
    for r in range(rings - 2):
        base = 1 + r * segments
        nxt = base + segments
        for s in range(segments):
            s2 = (s + 1) % segments
            faces.append((base + s, nxt + s, nxt + s2, base + s2))
    last = 1 + (rings - 2) * segments
    bottom = len(verts) - 1
    for s in range(segments):
        faces.append((bottom, last + (s + 1) % segments, last + s))

    obj = mesh_from_data(name, verts, faces, material, smooth=True)
    obj.location = center
    return obj


def capsule(
    name: str,
    center: tuple[float, float, float],
    radius: float,
    length: float,
    material: str = MAT_BODY,
    axis: str = "Z",
    segments: int = 8,
) -> bpy.types.Object:
    """Rounded limb segment: a prism with domed caps, joined as one mesh."""
    half = max(0.0001, length / 2.0 - radius)
    verts: list[tuple[float, float, float]] = []
    faces: list[tuple[int, ...]] = []

    rings = [
        (-half - radius * 0.86, radius * 0.34),
        (-half - radius * 0.5, radius * 0.72),
        (-half, radius),
        (half, radius),
        (half + radius * 0.5, radius * 0.72),
        (half + radius * 0.86, radius * 0.34),
    ]
    for z, r in rings:
        for s in range(segments):
            a = (s / segments) * math.tau
            verts.append((math.cos(a) * r, math.sin(a) * r, z))
    for ri in range(len(rings) - 1):
        base = ri * segments
        nxt = base + segments
        for s in range(segments):
            s2 = (s + 1) % segments
            faces.append((base + s, nxt + s, nxt + s2, base + s2))
    # Caps.
    verts.append((0.0, 0.0, -half - radius))
    bottom_tip = len(verts) - 1
    for s in range(segments):
        faces.append((bottom_tip, (s + 1) % segments, s))
    verts.append((0.0, 0.0, half + radius))
    top_tip = len(verts) - 1
    top_base = (len(rings) - 1) * segments
    for s in range(segments):
        faces.append((top_tip, top_base + s, top_base + (s + 1) % segments))

    obj = mesh_from_data(name, verts, faces, material, smooth=True)
    rot = [0.0, 0.0, 0.0]
    if axis.upper() == "X":
        rot[1] = 90.0
    elif axis.upper() == "Y":
        rot[0] = 90.0
    obj.location = center
    obj.rotation_euler = tuple(math.radians(a) for a in rot)
    return obj


def socket(name: str, location: tuple[float, float, float]) -> bpy.types.Object:
    """
    Empty marker exported with the GLB.

    The client reads `SOCKET_muzzle`, `SOCKET_eject` and `SOCKET_grip` to attach
    muzzle flashes, shell ejection and the left-hand IK target, so those points
    live in the art rather than being duplicated as magic numbers in code.
    """
    empty = bpy.data.objects.new(f"SOCKET_{name}", None)
    empty.empty_display_type = "PLAIN_AXES"
    empty.empty_display_size = 0.02
    empty.location = location
    _link(empty)
    return empty


