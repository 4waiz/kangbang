def reset_scene() -> None:
    """Empty the file completely so a generator always starts clean."""
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.length_unit = "METERS"
    # A single sun so the .blend is viewable when opened by a human.
    sun_data = bpy.data.lights.new("NeonSun", type="SUN")
    sun_data.energy = 3.0
    sun = bpy.data.objects.new("NeonSun", sun_data)
    sun.rotation_euler = (math.radians(55), 0.0, math.radians(35))
    scene.collection.objects.link(sun)


def _link(obj: bpy.types.Object) -> None:
    bpy.context.scene.collection.objects.link(obj)


def mesh_from_data(
    name: str,
    verts: list[tuple[float, float, float]],
    faces: list[tuple[int, ...]],
    material: str,
    smooth: bool = False,
) -> bpy.types.Object:
    """Create an object from explicit vertex/face data."""
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.validate(verbose=False)
    mesh.update()
    if smooth:
        for poly in mesh.polygons:
            poly.use_smooth = True
    mesh.materials.append(get_material(material))
    obj = bpy.data.objects.new(name, mesh)
    _link(obj)
    return obj


