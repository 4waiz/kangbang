def reorient(mode: str) -> None:
    """
    Rotate the whole scene so the exported glTF lands on the engine's axes.

    Blender is Z-up; glTF is Y-up, and the exporter converts with
    (gx, gy, gz) = (bx, bz, -by). That conversion is why authoring convention
    matters, and why this step exists rather than a fudge factor in the client:

      'yup'  - authored with +Y up and -Z forward (weapons, arms, props).
               Rotating +90 degrees about Blender X maps (x, y, z) to (x, -z, y),
               which after the exporter's conversion reproduces the authored
               axes exactly. Without it a rifle exports pointing at the floor.

      'face' - authored Blender-native (Z up) but facing -Y (characters).
               Rotating 180 degrees about Blender Z leaves the model facing -Z
               after export, which is the engine's forward direction.

    Call immediately before export_glb(), after all joins.
    """
    if mode == "yup":
        matrix = mathutils.Euler((math.radians(90), 0.0, 0.0)).to_matrix().to_4x4()
    elif mode == "face":
        matrix = mathutils.Euler((0.0, 0.0, math.radians(180))).to_matrix().to_4x4()
    else:
        return

    transformed_meshes: set[str] = set()
    for obj in list(bpy.data.objects):
        if obj.type == "MESH":
            # join() has already baked object transforms, so transforming the
            # mesh data is enough - and each mesh datablock must only be
            # transformed once even if several objects share it.
            if obj.data.name not in transformed_meshes:
                obj.data.transform(matrix)
                obj.data.update()
                transformed_meshes.add(obj.data.name)
            obj.location = (matrix @ obj.location.to_4d()).to_3d()
        elif obj.type == "EMPTY":
            obj.location = (matrix @ obj.location.to_4d()).to_3d()


def export_glb(name: str, save_blend: bool = True, objects: list[bpy.types.Object] | None = None) -> str:
    """Write <EXPORT_DIR>/<name>.glb and (optionally) the .blend source."""
    for obj in bpy.data.objects:
        if obj.type == "MESH" and not obj.data.uv_layers:
            add_uvs(obj)

    if objects is not None:
        for obj in bpy.data.objects:
            obj.select_set(False)
        for obj in objects:
            obj.select_set(True)

    if save_blend:
        blend_path = os.path.join(SOURCE_DIR, f"{name}.blend")
        bpy.ops.wm.save_as_mainfile(filepath=blend_path, check_existing=False, copy=True)

    glb_path = os.path.join(EXPORT_DIR, f"{name}.glb")
    kwargs = dict(
        filepath=glb_path,
        export_format="GLB",
        export_apply=True,
        export_yup=True,
        export_cameras=False,
        export_lights=False,
        export_extras=False,
        use_selection=objects is not None,
        export_normals=True,
        export_texcoords=True,
        export_materials="EXPORT",
        export_animations=True,
    )
    # Draco is what makes high-poly affordable here: it shrinks these meshes by
    # roughly 80%, and the client already requires the extension. Fall back
    # silently rather than failing the build if the encoder is unavailable.
    try:
        bpy.ops.export_scene.gltf(**kwargs, export_draco_mesh_compression_enable=True,
                                  export_draco_mesh_compression_level=6)
    except TypeError:
        bpy.ops.export_scene.gltf(**kwargs)
    except RuntimeError:
        bpy.ops.export_scene.gltf(**kwargs)

    size = os.path.getsize(glb_path)
    tris = sum(triangle_count(o) for o in bpy.data.objects if o.type == "MESH")
    log(f"exported {name}.glb  {size / 1024:.1f} KB  {tris} tris")
    return glb_path


def finish(
    name: str,
    parts: list[bpy.types.Object],
    smooth_angle: float = 38.0,
    lod_threshold: int = 2600,
    lod_ratio: float = 0.34,
    orient: str = "yup",
    recenter: bool = False,
) -> bpy.types.Object:
    """
    The common tail of every generator: join, shade, LOD, orient, export.

    Kept in one place because the order matters and is easy to get wrong.
    Smoothing has to happen after the join so a single angle threshold applies
    across the whole model, and the LOD has to be built before `reorient` so
    both meshes are transformed together.
    """
    obj = join(name, parts)
    weld(obj)
    smooth_by_angle(obj, smooth_angle)
    add_uvs(obj)

    if recenter:
        # World pickups spin about their own middle on a pedestal.
        lo = [min(v.co[i] for v in obj.data.vertices) for i in range(3)]
        hi = [max(v.co[i] for v in obj.data.vertices) for i in range(3)]
        offset = [(lo[i] + hi[i]) / 2.0 for i in range(3)]
        for vert in obj.data.vertices:
            for i in range(3):
                vert.co[i] -= offset[i]
        obj.data.update()

    tris = triangle_count(obj)
    if tris > lod_threshold:
        lod = decimate_copy(obj, f"{name}_LOD1", lod_ratio)
        smooth_by_angle(lod, smooth_angle)
        add_uvs(lod)

    reorient(orient)
    export_glb(name)
    return obj


def only_arg(flag: str) -> str | None:
    """Read `-- --only=<value>` from the Blender command line."""
    argv = sys.argv
    if "--" not in argv:
        return None
    for token in argv[argv.index("--") + 1:]:
        if token.startswith(f"--{flag}="):
            return token.split("=", 1)[1]
    return None


def vec(x: float, y: float, z: float) -> mathutils.Vector:
    return mathutils.Vector((x, y, z))
