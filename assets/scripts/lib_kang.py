def get_material(name: str) -> bpy.types.Material:
    """Fetch or create one of the library materials."""
    existing = bpy.data.materials.get(name)
    if existing is not None:
        return existing

    spec = MATERIAL_LIBRARY.get(name)
    if spec is None:
        spec = MATERIAL_LIBRARY[MAT_BODY]
    base_color, metallic, roughness, emission, emission_strength = spec

    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    # glTF writes doubleSided = not use_backface_culling. Every mesh here is a
    # closed solid, so culling backfaces halves the fragment work for free.
    mat.use_backface_culling = True
    nodes = mat.node_tree.nodes
    bsdf = nodes.get("Principled BSDF")
    if bsdf is None:
        bsdf = nodes.new("ShaderNodeBsdfPrincipled")
    bsdf.inputs["Base Color"].default_value = base_color
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    if "Emission Color" in bsdf.inputs and emission is not None:
        bsdf.inputs["Emission Color"].default_value = (*emission, 1.0)
        bsdf.inputs["Emission Strength"].default_value = emission_strength
    elif "Emission" in bsdf.inputs and emission is not None:
        bsdf.inputs["Emission"].default_value = (*emission, 1.0)
        if "Emission Strength" in bsdf.inputs:
            bsdf.inputs["Emission Strength"].default_value = emission_strength
    if base_color[3] < 1.0:
        mat.blend_method = "BLEND"
        if "Alpha" in bsdf.inputs:
            bsdf.inputs["Alpha"].default_value = base_color[3]
    return mat


